"""Turn the files in web/data/src/ into web/data/layers.js (standard library only).

Put in web/data/src/:
  name.geojson             a vector layer (WGS84 lon/lat), e.g. exported from GeoPandas with
                           gdf.to_crs(4326).to_file("name.geojson", driver="GeoJSON")
  name.png + name.json     a raster image overlay; name.json = {"bounds": [[south, west], [north, east]]}
  layers.json (optional)   per-layer settings: {"name": {"name": "...", "color": "#hex", "visible": true,
                           "props": ["col1", "col2"], "order": 1, "opacity": 0.6, "style": ..., "legend": ...,
                           "audience": "public"}}

Audience: every layer is internal-only unless layers.json gives it "audience": "public".
The public edition (tools/build_public.py) keeps only those, and only their "props".

Colour by a property ("style"), shown in the map legend:
  exact values:  {"by": "kind", "classes": [{"value": "a", "color": "#hex", "label": "A"}, ...]}
  thresholds:    {"by": "people", "bins": [100, 1000], "colors": ["#c6dbef", "#6baed6", "#08519c"],
                  "labels": ["< 100", "100 - 1,000", "> 1,000"]}      (len(colors) = len(bins) + 1)
Image layers can't be coloured by value; give them a manual legend instead:
  "legend": [{"color": "#hex", "label": "..."}]

    python3 tools/build_layers.py
"""
import argparse
import base64
import json
from pathlib import Path

WEB = Path(__file__).resolve().parent.parent / "web"
SRC = WEB / "data" / "src"
OUT = WEB / "data" / "layers.js"
PALETTE = ["#1d4ed8", "#ea580c", "#059669", "#db2777", "#7c3aed", "#0891b2", "#ca8a04", "#4b5563"]
EXAMPLE = {
    "id": "example", "name": "Example layer (delete me)", "type": "geojson", "color": "#7c3aed",
    "visible": True, "props": ["name", "note"], "audience": "public",
    "style": {"by": "kind", "classes": [
        {"value": "area", "color": "#7c3aed", "label": "Example class A"},
        {"value": "point", "color": "#db2777", "label": "Example class B"},
    ]},
    "data": {"type": "FeatureCollection", "features": [
        {"type": "Feature", "properties": {"name": "Example area", "kind": "area", "note": "Placeholder shape. Replace with your own layer."},
         "geometry": {"type": "Polygon", "coordinates": [[[4.3, 50.8], [4.42, 50.8], [4.42, 50.88], [4.3, 50.88], [4.3, 50.8]]]}},
        {"type": "Feature", "properties": {"name": "Example point", "kind": "point", "note": "Points are drawn as circles."},
         "geometry": {"type": "Point", "coordinates": [4.36, 50.84]}},
    ]},
}


def public_only(layer):
    """Drop every feature property the layer does not list in "props" (nothing leaks by accident)."""
    if layer["type"] == "geojson":
        keep = set(layer.get("props", []))
        style_by = (layer.get("style") or {}).get("by")
        if style_by:
            keep.add(style_by)
        for f in layer["data"]["features"]:
            f["properties"] = {k: v for k, v in (f.get("properties") or {}).items() if k in keep}
    else:
        # Inline the image: the public build does not ship web/data/src/.
        data = base64.b64encode((WEB / layer["url"]).read_bytes()).decode()
        layer["url"] = f"data:image/png;base64,{data}"
    return layer


def main(audience="internal", out=OUT):
    SRC.mkdir(parents=True, exist_ok=True)
    settings_file = SRC / "layers.json"
    settings = json.loads(settings_file.read_text()) if settings_file.exists() else {}
    layers = []
    for path in sorted(SRC.glob("*.geojson")):
        layers.append({"id": path.stem, "name": path.stem.replace("_", " "), "type": "geojson",
                       "data": json.loads(path.read_text())})
    for path in sorted(SRC.glob("*.png")):
        meta = json.loads(path.with_suffix(".json").read_text())
        layers.append({"id": path.stem, "name": path.stem.replace("_", " "), "type": "image",
                       "url": f"data/src/{path.name}", "bounds": meta["bounds"]})
    for i, layer in enumerate(layers):
        layer["color"] = PALETTE[i % len(PALETTE)]
        layer.update(settings.get(layer["id"], {}))
    layers.sort(key=lambda layer: layer.get("order", 999))
    if not layers:
        layers = [EXAMPLE]
    if audience == "public":
        layers = [public_only(layer) for layer in layers if layer.get("audience") == "public"]
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("// Generated by tools/build_layers.py from web/data/src/. Do not edit by hand.\n"
                   f"window.TOOL_AUDIENCE = {json.dumps(audience)};\n"
                   "window.TOOL_LAYERS = " + json.dumps(layers, ensure_ascii=False, separators=(",", ":")) + ";\n")
    size = out.stat().st_size / 1e6
    print(f"{audience}: {len(layers)} layer(s) -> {out} ({size:.1f} MB)")
    for layer in layers:
        n = len(layer["data"]["features"]) if layer["type"] == "geojson" else "image"
        print(f"  {layer['id']}: {n}")
    if size > 15:
        print("  warning: over 15 MB; simplify geometries (gdf.simplify) or round coordinates")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--audience", choices=["internal", "public"], default="internal")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()
    main(args.audience, args.out)
